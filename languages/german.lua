Markiere deine Gegenstände als Favoriten und halte sie in den von dir gewählten Slots.

Anleitung:
    - Nimm einen Gegenstand mit der Maus auf, drücke die Favoriten-Taste (Standard V) und klicke den Slot an, in dem er bleiben soll.
    - Drücke die Favoriten-Taste + Klick erneut, um den Favoriten zu entfernen.
    - Nimm einen Gegenstand auf, drücke die Favoriten-Taste + klicke einen anderen Slot, um ihn zu verschieben.
    - Drücke CTRL + SHIFT + Z, um alle Favoriten zu löschen. (Nützlich bei Fehlern)

- Du kannst mehrere Gegenstände favorisieren, jeweils in einem eigenen Slot.
- Gegenstände in Rucksäcken können nicht favorisiert werden.
